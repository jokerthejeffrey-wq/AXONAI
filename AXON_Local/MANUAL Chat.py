"""Compatibility launcher for AXON-only chat.

This file no longer starts a pretrained teacher model. Every user-facing
assistant reply is generated by AXON's own autoregressive Transformer.
"""
from pathlib import Path
import runpy

CHAT = Path(__file__).resolve().with_name("CHAT.py")
if not CHAT.is_file():
    raise SystemExit("CHAT.py is missing. Keep it beside MANUAL Chat.py.")

runpy.run_path(str(CHAT), run_name="__main__")
